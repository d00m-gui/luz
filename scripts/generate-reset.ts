import { readFileSync, writeFileSync } from "node:fs";
import { dirname, join } from "node:path";

const TOOLS_DIR = join(import.meta.dir, "..", "src", "tools");
const OUT_FILE = join(TOOLS_DIR, "reset-css.generated.ts");

function resolveImports(cssPath: string): string {
  const css = readFileSync(cssPath, "utf8");
  return css.replace(/^@import\s+"(.+?)";$/gm, (_m, relPath) =>
    resolveImports(join(dirname(cssPath), relPath)),
  );
}

function toExport(name: string, cssFile: string): string {
  const css = resolveImports(join(TOOLS_DIR, cssFile));
  return `export const ${name} = ${JSON.stringify(css)};\n`;
}

const names = [
  ...readFileSync(join(TOOLS_DIR, "components.css"), "utf8").matchAll(
    /^@import "\.\/components\/(.+)\.css";$/gm,
  ),
].map((match) => match[1]!);
const header = "// Generated by scripts/generate-reset.ts.\n\n";
const body =
  toExport("RESET", "reset.css") +
  `export const COMPONENTS = ${JSON.stringify(
    Object.fromEntries(
      names.map((name) => [
        name,
        resolveImports(join(TOOLS_DIR, "components", `${name}.css`)),
      ]),
    ),
  )};\n`;
writeFileSync(
  join(TOOLS_DIR, "component-names.generated.ts"),
  header +
    `export const COMPONENT_NAMES = ${JSON.stringify(names)} as const;\n` +
    `export type LuzComponent = Exclude<(typeof COMPONENT_NAMES)[number], \`_\${string}\`> | "_print";\n`,
);

writeFileSync(OUT_FILE, header + body);
console.log(`generated ${OUT_FILE}`);
